//go:build ignore

// gen_timezones writes timezones.go: the guide time zone's choices, as the
// app's Stalker manifest offers them, read from the app's
// adapters/api/fixtures/adapters.json beside Foyer. Run it with
// `go generate ./internal/iptv` after the app's list changes; the adapters
// fixture test fails until it is.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
)

const fixture = "../../../../loge/src/adapters/api/fixtures/adapters.json"

func main() {
	raw, err := os.ReadFile(fixture)
	if err != nil {
		log.Fatalf("the app's adapters fixture: %v", err)
	}
	var f struct {
		Adapters []struct {
			ID     string `json:"id"`
			Fields []struct {
				Key     string `json:"key"`
				Options []struct {
					Value string `json:"value"`
					Label string `json:"label"`
				} `json:"options"`
			} `json:"fields"`
		} `json:"adapters"`
	}
	if err := json.Unmarshal(raw, &f); err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by gen_timezones.go from the app's adapters/api/fixtures/adapters.json; DO NOT EDIT.\n\n")
	out.WriteString("package iptv\n\nimport \"foyer/internal/adapters\"\n\n")
	out.WriteString("// timeZones are the guide time zone's choices, the app's to the byte: as the\n// portal says, then every IANA zone by the id the app's list spells it.\n")
	out.WriteString("var timeZones = []adapters.Option{\n")
	found := false
	for _, a := range f.Adapters {
		if a.ID != "iptv/stalker" {
			continue
		}
		for _, field := range a.Fields {
			if field.Key != "timeZone" {
				continue
			}
			for _, o := range field.Options {
				fmt.Fprintf(&out, "\t{Value: %q, Label: %q},\n", o.Value, o.Label)
				found = true
			}
		}
	}
	if !found {
		log.Fatal("the fixture has no iptv/stalker timeZone options")
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("timezones.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
